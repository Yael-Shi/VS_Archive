@dataclass(frozen=True)
class PublicContent:
    title: str
    body: str


def _merge_block(key: str, row: PublicContentBlock | None) -> PublicContent:
    default = DEFAULT_PUBLIC_CONTENT[key]
    if row is None:
        return PublicContent(title=default["title"], body=default["body"])
    title = row.title if row.title else default["title"]
    body = row.body if row.body else default["body"]
    return PublicContent(title=title, body=body)


def get_public_content(key: str) -> PublicContent:
    if key not in DEFAULT_PUBLIC_CONTENT:
        raise KeyError(f"Unknown public content key: {key}")
    row = PublicContentBlock.objects.filter(key=key).first()
    return _merge_block(key, row)


def get_all_public_content() -> dict[str, PublicContent]:
    rows = PublicContentBlock.objects.filter(
        key__in=DEFAULT_PUBLIC_CONTENT.keys()
    )
    by_key = {row.key: row for row in rows}
    return {
        key: _merge_block(key, by_key.get(key))
        for key in DEFAULT_PUBLIC_CONTENT
    }


def save_public_content_from_post(post_data) -> None:
    for block_def in EDITABLE_PUBLIC_BLOCKS:
        key = block_def["key"]
        title = (post_data.get(f"title_{key}") or "").strip()
        body = (post_data.get(f"body_{key}") or "").strip()
        PublicContentBlock.objects.update_or_create(
            key=key,
            defaults={"title": title, "body": body},
        )
